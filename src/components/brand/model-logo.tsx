/** Model/brand artwork at a square size, with an initial as the fallback. */
export function ModelLogo({
  brand,
  name,
  size = 44,
  variant = "badge",
  className,
}: ModelLogoProps) {
  const common = {
    width: size,
    height: size,
    "aria-hidden": true as const,
    className: cn("shrink-0", className),
  };

  switch (brand) {
    case "deepseek":
      return <DeepSeek {...common} />;
    case "minimax":
      if (variant === "plain") {
        return (
          <Image
            src="/dashboard/logo-minimax.webp"
            alt=""
            width={size}
            height={size}
            className={cn("shrink-0", className)}
          />
        );
      }
      return <MiniMax {...common} className={cn(common.className, "rounded-md")} />;
    case "openai":
      // The artwork is 36 units inside a 44 frame in Figma, so it sits slightly inset.
      return (
        <span
          aria-hidden="true"
          style={{ width: size, height: size }}
          className={cn("inline-flex shrink-0 items-center justify-center text-primary", className)}
        >
          <OpenAI width={Math.round(size * 0.82)} height={Math.round(size * 0.82)} />
        </span>
      );
    case "gemma":
      return (
        <Image
          src="/dashboard/logo-gemma.webp"
          alt=""
          width={size}
          height={size}
          className={cn("shrink-0", className)}
        />
      );
    default:
      return (
        <span
          aria-hidden="true"
          style={{ width: size, height: size }}
          className={cn(
            "inline-flex shrink-0 items-center justify-center rounded-md bg-active text-label font-semibold text-nav-active",
            className,
          )}
        >
          {name.trim().charAt(0).toUpperCase()}
        </span>
      );
  }
}
