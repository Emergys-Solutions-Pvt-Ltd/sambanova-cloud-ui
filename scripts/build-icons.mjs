#!/usr/bin/env node
/**
 * Builds the icon registry from the Figma SVG exports in assets/icons/.
 *
 *   assets/icons/<name>.svg  →  SVGO  →  src/components/ui/icon/icon-data.generated.ts
 *
 * Every color is forced to currentColor so icons inherit text color. Run with
 * `npm run icons` after adding or changing an SVG; the output is committed.
 */
import fs from "node:fs";
import path from "node:path";

import { optimize } from "svgo";

const SOURCE = path.resolve("assets/icons");
const OUTPUT = path.resolve("src/components/ui/icon/icon-data.generated.ts");

const svgoConfig = {
  multipass: true,
  floatPrecision: 2,
  plugins: [
    { name: "preset-default", params: { overrides: { removeViewBox: false } } },
    "removeDimensions",
    "removeXMLNS",
    { name: "convertColors", params: { currentColor: true } },
  ],
};

const attr = (tag, name) => tag.match(new RegExp(`\\s${name}="([^"]*)"`))?.[1];

const icons = {};
for (const file of fs
  .readdirSync(SOURCE)
  .filter((f) => f.endsWith(".svg"))
  .sort()) {
  const name = path.basename(file, ".svg");
  const { data } = optimize(fs.readFileSync(path.join(SOURCE, file), "utf8"), {
    ...svgoConfig,
    path: file,
  });
  const open = data.match(/^<svg[^>]*>/)[0];
  const body = data.slice(open.length, data.lastIndexOf("</svg>"));
  if (/#[0-9a-f]{3,8}\b|rgb\(/i.test(body)) {
    throw new Error(`${file}: hard-coded color left after optimisation`);
  }
  icons[name] = {
    viewBox: attr(open, "viewBox"),
    fill: attr(open, "fill") ?? "currentColor",
    stroke: attr(open, "stroke"),
    strokeWidth: attr(open, "stroke-width"),
    strokeLinecap: attr(open, "stroke-linecap"),
    strokeLinejoin: attr(open, "stroke-linejoin"),
    body,
  };
}

const json = JSON.stringify(icons, null, 2).replace(/"(\w+)":/g, "$1:");
fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });
fs.writeFileSync(
  OUTPUT,
  `// GENERATED by scripts/build-icons.mjs from assets/icons/*.svg. Do not edit by hand.\n\n` +
    `export interface IconDefinition {\n  viewBox: string;\n  fill: string;\n  stroke?: string;\n  strokeWidth?: string;\n  strokeLinecap?: string;\n  strokeLinejoin?: string;\n  body: string;\n}\n\n` +
    `export const iconData = ${json} as const satisfies Record<string, IconDefinition>;\n\n` +
    `export type IconName = keyof typeof iconData;\n\n` +
    `export const iconNames = Object.keys(iconData) as IconName[];\n`,
);

const before = fs
  .readdirSync(SOURCE)
  .reduce((sum, f) => sum + fs.statSync(path.join(SOURCE, f)).size, 0);
const after = Object.values(icons).reduce((sum, icon) => sum + icon.body.length, 0);
// eslint-disable-next-line no-console -- CLI output
console.log(
  `${Object.keys(icons).length} icons → ${path.relative(process.cwd(), OUTPUT)} (${before} → ~${after} bytes of markup)`,
);
